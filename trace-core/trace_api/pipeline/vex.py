"""CSAF 2.0 VEX generation.

Produces a schema-conformant ``csaf_vex`` document from TRACE findings. The
structure mirrors ``lib/vex.ts`` on the frontend so a document generated by the
API is byte-compatible with the one previewed in the UI.
"""

from __future__ import annotations

import json
import re
from typing import Any

CSAF_SCHEMA = "https://docs.oasis-open.org/csaf/csaf/v2.0/schema/csaf.json"
PRODUCT_ID = "CSAFPID-0001"


def document_id(scan: dict[str, Any], scope: str) -> str:
    suffix = {"finding": "F", "actionable": "A", "all": "ALL"}.get(scope, "ALL")
    date = (scan.get("scannedAt") or "1970-01-01")[:10]
    return f"TRACE-VEX-{date}-{scan.get('commit', '0000000')}-{suffix}"


def file_name(scan: dict[str, Any], scope: str) -> str:
    return f"{document_id(scan, scope)}.csaf.json"


def _score_vector(cvss: float) -> dict[str, str]:
    return {
        "baseScore": f"{cvss:.1f}",
        "baseSeverity": "critical" if cvss >= 9 else "high" if cvss >= 7 else "medium" if cvss >= 4 else "low",
        "version": "3.1",
        "vectorString": (
            "CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:U/C:H/I:H/A:H"
            if cvss >= 9
            else "CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:U/C:H/I:N/A:N"
            if cvss >= 7
            else "CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:U/C:N/I:N/A:L"
        ),
    }


def _status(finding: dict[str, Any]) -> tuple[str, dict[str, str] | None]:
    if finding.get("reachability") == "suppressed" or finding.get("verdict") not in ("affected", "not_affected"):
        # Operator exclusion and missing evidence do not prove non-affection.
        return ("under_investigation", None)
    if finding.get("verdict") == "affected" and finding.get("reachability") == "reachable":
        return ("known_affected", None)
    if finding.get("verdict") == "affected":
        return ("under_investigation", None)
    return (
        "known_not_affected",
        {
            "category": "vulnerable_code_cannot_be_controlled_by_adversary",
            "details": finding.get("blocker") or finding.get("evidence", {}).get("headline", ""),
        },
    )


def build_vex(scan: dict[str, Any], findings: list[dict[str, Any]], scope: str) -> str:
    scanned_at = scan.get("scannedAt") or "1970-01-01T00:00:00Z"
    commit_long = scan.get("commitLong", "").ljust(64, "0")
    product_name = f"{scan.get('repository', 'repository')}@{scan.get('commit', '')}"

    vulns = []
    for finding in findings:
        status, justification = _status(finding)
        evidence = finding.get("evidence", {})
        notes: list[dict[str, Any]] = [
            {
                "category": "description",
                "text": (
                    f"{finding['cve']} in {finding['packageName']}@{finding['version']} "
                    f"({finding.get('ecosystem', 'maven')}). {evidence.get('headline', '')}"
                ),
            },
            {
                "category": "other",
                "title": {"en": "TRACE AI evidence", "ru": "Обоснование TRACE AI"},
                "text": "\n".join(
                    [
                        f"model: {evidence.get('model', '')} ({evidence.get('runtime', '')})",
                        f"confidence: {float(evidence.get('confidence', 0.0)):.2f}",
                        "",
                        evidence.get("reasoning", ""),
                    ]
                ),
            },
        ]
        if evidence.get("taintSource"):
            propagation = evidence.get("taintPropagation") or []
            notes.append(
                {
                    "category": "other",
                    "title": {"en": "Taint source", "ru": "Источник недоверенных данных"},
                    "text": "\n".join([evidence["taintSource"]] + [f"{i + 1}. {s}" for i, s in enumerate(propagation)]),
                }
            )
        if evidence.get("sink"):
            notes.append(
                {
                    "category": "other",
                    "title": {"en": "Sink", "ru": "Уязвимый символ"},
                    "text": evidence["sink"],
                }
            )
        if finding.get("suppressReason"):
            notes.append(
                {
                    "category": "other",
                    "title": {"en": "Suppression", "ru": "Подавление"},
                    "text": finding["suppressReason"],
                }
            )

        product_ref: dict[str, Any] = {"product_id": PRODUCT_ID}
        if justification:
            product_ref["justifications"] = [justification]

        entry: dict[str, Any] = {
            "cve": finding["cve"],
            "cwe": [{"id": c, "name": c} for c in finding.get("cwe", [])],
            "discovery_date": scanned_at,
            "notes": notes,
            "product_status": {status: [product_ref]},
            "scores": [{"cvss_v3": _score_vector(float(finding.get("cvss", 0.0)))}],
            "remediations": [
                {
                    "category": "vendor_fix" if i == 0 else "mitigation",
                    "details": detail,
                    "product_ids": [PRODUCT_ID],
                    "url": f"https://trace.security/remediation/{finding['cve'].lower()}",
                }
                for i, detail in enumerate(evidence.get("remediation", []))
            ],
        }
        if evidence.get("nativeObservations") or evidence.get('webObservations'):
            entry.pop("scores",None)
        if not re.fullmatch(r"CVE-[0-9]{4}-[0-9]{4,}",finding["cve"]):
            entry.pop("cve",None)
            entry["ids"]=[{"system_name":"TRACE rule","text":finding["cve"]}]
        if status == "known_not_affected":
            entry["threats"] = [
                {
                    "category": "impact",
                    "details": (
                        "No exploitable path from a live entrypoint to the vulnerable symbol "
                        "exists at this revision. Re-evaluate if entrypoints or dependency "
                        "versions change."
                    ),
                }
            ]
        vulns.append(entry)

    document = {
        "$schema": CSAF_SCHEMA,
        "document": {
            "category": "csaf_vex",
            "csaf_version": "2.0",
            "title": f"TRACE VEX — {product_name} ({scope})",
            "publisher": {
                "category": "vendor",
                "name": "TRACE Security",
                "namespace": "https://trace.security",
                "contact_details": "https://trace.security/security.txt",
            },
            "tracking": {
                "id": document_id(scan, scope),
                "status": "final",
                "version": "1",
                "initial_release_date": scanned_at,
                "current_release_date": scanned_at,
                "generator": {
                    "engine": {"name": "TRACE", "version": "3.4.0"},
                    "date": scanned_at,
                },
                "revision_history": [
                    {
                        "date": scanned_at,
                        "number": "1",
                        "summary": {
                            "en": "Initial VEX publication from automated reachability triage.",
                            "ru": "Первичная публикация VEX по результатам автоматического триажа достижимости.",
                        },
                    }
                ],
                "status_notes": [
                    {
                        "category": "legal_disclaimer",
                        "text": (
                            "TRACE statements are produced by static reachability analysis and "
                            "local model inference. They describe this repository revision and are "
                            "re-evaluated on every scan."
                        ),
                        "title": {"en": "Scope of assurance", "ru": "Границы гарантий"},
                    }
                ],
            },
            "distribution": {
                "tlp": {"label": "WHITE"},
                "text": "Публикуется в закрытом контуре клиента. Содержит пути внутреннего репозитория.",
            },
            "notes": [
                {
                    "category": "legal_disclaimer",
                    "text": (
                        "This document satisfies the minimum requirements of CSAF 2.0 for VEX. "
                        "It is not a substitute for a security advisory."
                    ),
                },
                {
                    "category": "other",
                    "title": {"en": "Analysis configuration", "ru": "Конфигурация анализа"},
                    "text": "\n".join(
                        [
                            f"commit: {scan.get('commitLong', '')}",
                            f"pipeline: {scan.get('pipeline', '')}",
                            f"branch: {scan.get('branch', '')}",
                            f"sbom: {scan.get('sbom', '')}",
                            f"inference: {scan.get('aiRuntime', {}).get('model', '')}",
                            f"network egress: {scan.get('aiRuntime', {}).get('egress', '0 bytes')}",
                        ]
                    ),
                },
            ],
            "references": [
                {
                    "category": "self",
                    "summary": {
                        "en": "TRACE VEX generated from the repository call graph.",
                        "ru": "Документ VEX сформирован по графу вызовов репозитория.",
                    },
                    "url": f"https://trace.security/vex/{document_id(scan, scope)}",
                },
                {
                    "category": "external",
                    "summary": {"en": "CISA VEX use cases", "ru": "Варианты применения VEX (CISA)"},
                    "url": "https://www.cisa.gov/sites/default/files/publications/VEX_Use_Cases_Aprill2022.pdf",
                },
            ],
        },
        "product_tree": {
            "full_product_names": [
                {
                    "name": product_name,
                    "product_id": PRODUCT_ID,
                    "product_identification_helper": {
                        "cpe": f"cpe:2.3:a:acme:telemetry-api:{scan.get('commit', '')}:*:*:*:*:*:*:*",
                        "hashes": [
                            {"algorithm": "SHA-256", "value": commit_long[:64]},
                        ],
                    },
                }
            ]
        },
        "vulnerabilities": vulns,
    }
    return json.dumps(document, ensure_ascii=False, indent=2)
